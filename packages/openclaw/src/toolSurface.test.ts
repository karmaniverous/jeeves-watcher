/**
 * @module plugin/toolSurface.test
 * Agent-facing surface: every registered tool's name, description, parameters, `catalogMode` and registration options, and the injected prompt rules, are pinned in `test/surface-0.18.0/`, and the differences from what plugin 0.17.0 registered (`test/baseline-0.17.0/`) are rendered to `test/surface-0.18.0/deltas.md`: the reviewed list of agent-facing changes (spec #281 A6). Any change to the surface changes these files.
 */

import { readFileSync } from 'node:fs';

import type {
  PluginApi,
  PromptBuildHandler,
  ToolDescriptor,
  ToolRegistrationOptions,
} from '@karmaniverous/jeeves';
import { describe, expect, it } from 'vitest';

import register from './index.js';
import { renderSurfaceDiff, type ToolSurface } from './test/surfaceDiff.js';

const baseline = (file: string) =>
  readFileSync(
    new URL(`./test/baseline-0.17.0/${file}`, import.meta.url),
    'utf8',
  );

const baselineTools = JSON.parse(baseline('tools.json')) as ToolSurface[];
const baselineRules = baseline('promptRules.md');

/** Tool renames (D77, Design 14): each 0.17.0 name and its current name. */
const RENAMES: Readonly<Record<string, string>> = {
  watcher_enrich: 'watcher_set_metadata',
  watcher_validate: 'watcher_validate_config',
  watcher_issues: 'watcher_list_issues',
  watcher_vcs_status: 'watcher_get_vcs_status',
  watcher_vcs_history: 'watcher_list_vcs_history',
  watcher_vcs_show: 'watcher_show_vcs_file',
  watcher_vcs_diff: 'watcher_diff_vcs',
  watcher_vcs_revert: 'watcher_revert_vcs',
  watcher_vcs_exclude: 'watcher_exclude_vcs_path',
  watcher_vcs_check: 'watcher_check_vcs_exclusion',
};

/** Register the plugin against a capturing API. */
async function capture(): Promise<{ tools: ToolSurface[]; rules: string }> {
  const tools: ToolSurface[] = [];
  const hooks: [string, unknown][] = [];
  const api: PluginApi = {
    registerTool: (tool: ToolDescriptor, options?: ToolRegistrationOptions) => {
      const { catalogMode } = tool as ToolDescriptor & { catalogMode?: string };
      tools.push({
        name: tool.name,
        description: tool.description,
        parameters: tool.parameters,
        ...(catalogMode ? { catalogMode } : {}),
        ...(options ? { options } : {}),
      });
    },
    on: (name: string, handler: unknown) => {
      hooks.push([name, handler]);
    },
    logger: { warn: () => undefined },
  };
  register(api);
  const hook = hooks.find(([name]) => name === 'before_prompt_build');
  const handler = hook?.[1] as PromptBuildHandler;
  const result = (await handler({ prompt: '', messages: [] }, {})) as {
    appendSystemContext?: string;
  };
  return { tools, rules: result.appendSystemContext ?? '' };
}

/** The prompt-rules lines that changed, as a Markdown section. */
function rulesDiff(before: string, after: string): string {
  const was = before.split('\n');
  const now = after.split('\n');
  const removed = was.filter((line) => !now.includes(line));
  const added = now.filter((line) => !was.includes(line));
  return [
    '## Prompt rules',
    '',
    ...(removed.length + added.length === 0
      ? ['- unchanged']
      : [
          ...removed.map((line) => `- removed: ${JSON.stringify(line)}`),
          ...added.map((line) => `- added: ${JSON.stringify(line)}`),
        ]),
    '',
  ].join('\n');
}

describe('plugin agent-facing surface', async () => {
  const { tools, rules } = await capture();

  it('matches the pinned 0.18.0 tool surface', async () => {
    await expect(`${JSON.stringify(tools, null, 2)}\n`).toMatchFileSnapshot(
      './test/surface-0.18.0/tools.json',
    );
  });

  it('matches the pinned 0.18.0 prompt rules', async () => {
    await expect(rules).toMatchFileSnapshot(
      './test/surface-0.18.0/promptRules.md',
    );
  });

  it('lists every difference from 0.17.0 in deltas.md', async () => {
    const report = [
      '# Plugin agent-facing changes since 0.17.0',
      '',
      'Generated by `toolSurface.test.ts`; reviewed in the PR that changes it.',
      '',
      renderSurfaceDiff(baselineTools, tools, RENAMES),
      rulesDiff(baselineRules, rules),
    ].join('\n');
    await expect(report).toMatchFileSnapshot('./test/surface-0.18.0/deltas.md');
  });

  it('renames no tool outside the D77 list and drops none', () => {
    expect(tools.map((t) => t.name)).toEqual(
      baselineTools.map((t) => RENAMES[t.name] ?? t.name),
    );
  });
});
